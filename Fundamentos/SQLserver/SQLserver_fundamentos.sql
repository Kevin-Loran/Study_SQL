/*FAZENDO CONSULTAS COM JOIN*/

SELECT	A.NOME, 
		A.SEXO, 
		T.TIPO, 
		T.NUMERO , 
		E.UF
FROM ALUNO A
INNER JOIN ENDERECO E
ON A.IDALUNO = E.ID_ALUNO
INNER JOIN TELEFONE T
ON A.IDALUNO = T.IDALUNO
GO

