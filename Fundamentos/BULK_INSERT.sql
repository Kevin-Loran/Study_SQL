SELECT 
    IDCONTA,
    SUM(CASE WHEN TIPO = 'D' THEN VALOR * 1 ELSE VALOR * -1 END) AS SALDO,
    CASE 
        WHEN SUM(CASE WHEN TIPO = 'C' THEN VALOR ELSE -VALOR END) >= 0 THEN 'CREDOR'
        ELSE 'DEVEDOR'
    END AS SITUACAO

FROM CONTA
GROUP BY IDCONTA;
GO


