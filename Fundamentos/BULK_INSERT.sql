SELECT IDCONTA, VALOR, TIPO,
CHARINDEX('D', TIPO) AS DEBITO,
CHARINDEX('C', TIPO) AS CREDITO,
CHARINDEX('C', TIPO) * 2 - 1 AS MULTIPLICADOR
FROM CONTA
GO

SELECT IDCONTA, 
       SUM(VALOR * (CHARINDEX('C', TIPO) * 2 - 1)) AS SALDO
FROM CONTA
