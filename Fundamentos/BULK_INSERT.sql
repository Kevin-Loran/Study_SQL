        WHEN SUM(CASE WHEN TIPO = 'C' THEN VALOR ELSE -VALOR END) >= 0 THEN 'CREDOR'
        ELSE 'DEVEDOR'
    END AS SITUACAO
FROM CONTA
GROUP BY IDCONTA;
GO

