SELECT C.IDCLIENTE, C.NOME_CLIENTE,
T.NUMERO_TELEFONE,CC.MARCA,CC.PLACA_CARRO,
CTC.COR_NOME
FROM CLIENTES C
INNER JOIN TELEFONE_CLIENTES T
	ON C.IDCLIENTE = T.ID_CLIENTE 
INNER JOIN CARROS_CLIENTES CC
	ON C.IDCLIENTE = CC.ID_CLIENTE
INNER JOIN COR_TINTA_CARROS CTC
	ON CC.IDCARRO = CTC.ID_CARRO;